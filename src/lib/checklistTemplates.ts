/** How many things to do a template adds (items without sub-items). */
export function templateLeafCount(node: ChecklistTreeNode): number {
  const children = node.children ?? [];
  return children.length === 0 ? 1 : children.reduce((sum, c) => sum + templateLeafCount(c), 0);
}
